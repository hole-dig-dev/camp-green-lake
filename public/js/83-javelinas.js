'use strict';
/* public/js/83-javelinas.js -- javelina herd: a swarm of small hostile desert pigs hunting campers out on the
   lake. The rules (AI, bites, whacks, spawning) live in sim.js and run on the server when online, or right here
   in solo play -- this file only draws the herd, plays its sfx, and turns the dig key into a shovel swing when a
   live javelina is in reach. Generated by scripts/split-client.mjs; see ARCHITECTURE.md. */

/* ---------- rendering: up to 30 animals, 2 draw calls total (one InstancedMesh for bodies, one for legs) ---------- */
const JAV_MAX = 30; // matches sim.js's default herd size; the console command can ask for more, but the pool below is fixed
const JAV_BODY_GEO = mergeBoxes([
  [0.34, 0.28, 0.62, 0x33302c, 0, 0.28, 0],                                            // barrel body
  [0.22, 0.22, 0.24, 0x2c2925, 0, 0.30, 0.38],                                         // head
  [0.16, 0.10, 0.14, 0x565048, 0, 0.22, 0.56],                                         // pale snout
  [0.05, 0.09, 0.03, 0x2c2925, -0.08, 0.42, 0.42], [0.05, 0.09, 0.03, 0x2c2925, 0.08, 0.42, 0.42], // ears
  [0.02, 0.03, 0.09, 0xf2ecd8, -0.06, 0.19, 0.60], [0.02, 0.03, 0.09, 0xf2ecd8, 0.06, 0.19, 0.60],  // tiny tusks
  [0.34, 0.09, 0.16, 0xcfc6ac, 0, 0.40, 0.05],                                         // pale "collar" stripe (collared peccary)
  [0.10, 0.10, 0.14, 0x2c2925, 0, 0.30, -0.34],                                        // tail nub
  [0.03, 0.03, 0.03, 0x120f0c, -0.07, 0.34, 0.55], [0.03, 0.03, 0.03, 0x120f0c, 0.07, 0.34, 0.55], // eyes
]);
const JAV_LEG_GEO = new T.BoxGeometry(0.08, 0.26, 0.08);
const javBodyMesh = new T.InstancedMesh(JAV_BODY_GEO, mergedMat, JAV_MAX);
javBodyMesh.instanceMatrix.setUsage(T.DynamicDrawUsage); javBodyMesh.castShadow = true; javBodyMesh.frustumCulled = false; scene.add(javBodyMesh);
const javLegMat = M(0x26231f);
const javLegMesh = new T.InstancedMesh(JAV_LEG_GEO, javLegMat, JAV_MAX * 4);
javLegMesh.instanceMatrix.setUsage(T.DynamicDrawUsage); javLegMesh.castShadow = true; javLegMesh.frustumCulled = false; scene.add(javLegMesh);
const JAV_DRAW_R = 140; // PERF: like lizards, hidden past this range (still simulated/hunting, just not drawn)
const JAV_LEG_OFF = [[-0.13, 0.33], [0.13, 0.33], [-0.13, -0.22], [0.13, -0.22]]; // 4 legs, relative to the body's own facing
const jdo = new T.Object3D(), jlo = new T.Object3D(); // scratch objects, reused every slot every frame -- no per-frame allocation

/* JR: one render/interpolation slot per herd member (matches the server's fixed-size array by index, like showTruck
   interpolates trucks). JAVV: this frame's authoritative [x,z,h,state] snapshot -- from the server, or from the
   local sim in solo play. state 0 alive, 1 dying (tumble/poof), 2 gone. */
const JR = Array.from({ length: JAV_MAX }, () => ({ active: false, x: 0, z: 0, h: 0, tx: 0, tz: 0, th: 0, state: 0, dT: 0, hitT: 0, phase: Math.random() * 10 }));
let JAVV = [];
const JAV_LOCAL = { list: [] }; // solo/offline herd state; stepJavelinas mutates this in place, same idea as MONL

function stepSoloJavelinas(dt) {
  if (online()) return;
  const ev = []; SIM.stepJavelinas(JAV_LOCAL, [meSim()], clockT(), dt, ev);
  JAVV = JAV_LOCAL.list.map(j => [j.x, j.z, j.h, j.state]);
  for (const e of ev) javEvent(e);
}
function javFromServer(list, ev) {
  JAVV = (Array.isArray(list) ? list : []).slice(0, JAV_MAX).map(a => [num(a[0], -700, 700, 0), num(a[1], -700, 700, 0), num(a[2], -1e4, 1e4, 0), num(a[3], 0, 2, 0) | 0]);
  if (Array.isArray(ev)) for (const e of ev.slice(0, 40)) if (e && typeof e === 'object') javEvent(e);
}

/* relative direction ("ahead", "to your left", ...) for the warning toast -- no compass convention exists
   elsewhere in the game, so this is phrased against where the camper is actually facing */
function relDir(x, z) {
  const rel = Math.atan2(x - P.x, z - P.z) - P.fa, a = Math.atan2(Math.sin(rel), Math.cos(rel)), deg = a * 180 / Math.PI;
  return Math.abs(deg) < 35 ? 'ahead of you' : Math.abs(deg) > 145 ? 'behind you' : deg > 0 ? 'off to your right' : 'off to your left';
}
const JAV_KILL_XP = 8; // small XP reward per kill -- 30 of them add up without making the herd a farming trip
function javDust(x, z) { puff(x, groundAt(x, z) + 0.15, z, x, z, 7); }
function javSqueal(hi) { tone((hi ? 1300 : 900) + Math.random() * 300, 0.14, 'sawtooth', 0.2, hi ? 500 : 300); noise(0.14, 2200, 2, 0.16); }
function javSnort() { tone(130 + Math.random() * 40, 0.2, 'sawtooth', 0.15, 85); }
function javEvent(e) {
  switch (e.k) {
    case 'javSpawn': {
      const d = Math.hypot(e.x - P.x, e.z - P.z);
      toast(inCamp(P.x, P.z)
        ? `A herd of ${e.n} javelinas showed up out on the lake. You're safe here -- they won't cross the fence.`
        : `A herd of ${e.n} javelinas is charging in, ${relDir(e.x, e.z)}, about ${Math.round(d)} m out. Sprint for the fence, or fight them off -- two shovel hits kills one.`,
        'bad', 6500);
      tone(120, 0.5, 'sawtooth', 0.12, 55); logEv('javSpawn', { n: e.n, x: +e.x.toFixed(1), z: +e.z.toFixed(1) });
      break;
    }
    case 'javBite':
      if (e.id === myId()) { hurt(e.dmg, 'Bitten', 'A javelina bit you.'); javSqueal(false); }
      break;
    case 'javHit': { const s = JR[e.idx]; if (s) s.hitT = 0.25; javSqueal(true); break; }
    case 'javDeath': {
      const s = JR[e.idx]; if (s) { s.hitT = 0.3; javDust(s.x, s.z); }
      javSqueal(true);
      if (e.by === myId()) { addXP(JAV_KILL_XP); toast(`Javelina down. +${JAV_KILL_XP} XP`, 'good', 1800); sfx.coin(); logEv('javKill', {}); }
      break;
    }
    case 'javLeave': if (!inCamp(P.x, P.z)) toast('The herd is giving up. They\'re running off.', '', 3000); break;
  }
}

/* ---------- the shovel swing: hooked from the top of scoop() in 45-state.js, one line, so a javelina in reach
   gets whacked instead of the ground getting dug. Returns false (dig proceeds normally) when nothing's in reach. */
const JAV_SWING_R = 1.9, JAV_SWING_COS = 0.4; // reach, and "in front of you" (~65 degrees either side of your facing)
function nearestLiveJav() {
  let best = -1, bd = JAV_SWING_R * JAV_SWING_R;
  const fx = Math.sin(P.fa), fz = Math.cos(P.fa);
  for (let i = 0; i < JAVV.length; i++) {
    if (JAVV[i][3]) continue; // not alive
    const dx = JAVV[i][0] - P.x, dz = JAVV[i][1] - P.z, d2 = dx * dx + dz * dz; if (d2 > bd) continue;
    const d = Math.sqrt(d2) || 1; if ((dx / d) * fx + (dz / d) * fz < JAV_SWING_COS) continue; // behind/beside you: no swing
    bd = d2; best = i;
  }
  return best;
}
function javSwing() {
  const idx = nearestLiveJav(); if (idx < 0) return false;
  sfx.thud(); // the shovel connecting -- reuses the existing thud sfx rather than a new sound asset
  if (online()) wsSend({ t: 'whack', idx });
  else { const ev = []; SIM.whackJavelina(JAV_LOCAL, idx, P.x, P.z, ev, myId()); JAVV = JAV_LOCAL.list.map(j => [j.x, j.z, j.h, j.state]); for (const e of ev) javEvent(e); }
  return true;
}

/* ---------- console command: host-only in multiplayer (the whole console already is -- see canConsole()) ---------- */
command('javelinas', {
  usage: 'javelinas [count] [distance]', help: 'Spawn a herd of [30] javelinas [70] m out on the lake, coming for you. Everyone sees it; the camp fence keeps you safe.',
  run([n, d]) {
    const count = numArg(n, SIM.JAV_COUNT, 4, JAV_MAX), dist = numArg(d, 70, 20, 300); // capped at JAV_MAX: the fixed-size render pool above
    if (online()) wsSend({ t: 'javspawn', n: count, dist });
    else { const ev = []; SIM.spawnJavHerd(JAV_LOCAL, { x: P.x, z: P.z }, count, dist, ev); JAVV = JAV_LOCAL.list.map(j => [j.x, j.z, j.h, j.state]); for (const e of ev) javEvent(e); }
    return `Herd of ${count} javelinas spawned ${dist} m out.`;
  }
});

/* ---------- per-frame update: interpolate toward the latest snapshot (like showTruck) and build the instances ---------- */
function placeJavelina(i, s) {
  const visible = s.active && s.state !== 2 && nearCam(s.x, s.z, JAV_DRAW_R);
  if (!visible) {
    jdo.scale.setScalar(0); jdo.updateMatrix(); javBodyMesh.setMatrixAt(i, jdo.matrix);
    for (let L = 0; L < 4; L++) { jlo.scale.setScalar(0); jlo.updateMatrix(); javLegMesh.setMatrixAt(i * 4 + L, jlo.matrix); }
    return;
  }
  const y = groundAt(s.x, s.z), dying = s.state === 1, tumble = dying ? Math.min(1, s.dT / 0.9) : 0;
  const bob = s.state === 0 ? Math.abs(Math.sin(s.phase)) * 0.03 : 0;
  const hitPop = s.hitT > 0 ? 1 + Math.sin(s.hitT * 40) * 0.08 * (s.hitT / 0.25) : 1;
  jdo.position.set(s.x, y + 0.22 + bob - tumble * 0.18, s.z);
  jdo.rotation.set(tumble * Math.PI * 1.6, s.h, tumble * 1.1);
  jdo.scale.setScalar((1 - tumble * 0.4) * hitPop);
  jdo.updateMatrix(); javBodyMesh.setMatrixAt(i, jdo.matrix);
  for (let L = 0; L < 4; L++) {
    if (dying) { jlo.scale.setScalar(0); jlo.updateMatrix(); javLegMesh.setMatrixAt(i * 4 + L, jlo.matrix); continue; }
    const [lx, lz] = JAV_LEG_OFF[L];
    const swing = Math.sin(s.phase + (L % 2 ? Math.PI : 0) + (L < 2 ? 0 : Math.PI * 0.5)) * 0.5;
    const wx = s.x + Math.sin(s.h) * lz + Math.cos(s.h) * lx, wz = s.z + Math.cos(s.h) * lz - Math.sin(s.h) * lx;
    jlo.position.set(wx, y + 0.13, wz); jlo.rotation.set(swing, s.h, 0); jlo.scale.setScalar(1);
    jlo.updateMatrix(); javLegMesh.setMatrixAt(i * 4 + L, jlo.matrix);
  }
}
let javSnortT = 0, javWasIdle = true;
function updateJavelinas(dt) {
  if (!online()) stepSoloJavelinas(dt);
  const n = JAVV.length;
  // PERF: no herd out (by far the common case) and nothing left to fade out -- skip the instance-matrix rebuild
  // entirely instead of writing 30+120 idle matrices every frame for nothing.
  if (!n && javWasIdle) return;
  javWasIdle = !n;
  if (n && (javSnortT -= dt) <= 0 && !PARTY.on) { javSnortT = 1.2 + Math.random() * 2; if (nearCam(P.x, P.z, 45)) javSnort(); }
  for (let i = 0; i < JAV_MAX; i++) {
    const s = JR[i];
    if (i < n) {
      const [x, z, h, st] = JAVV[i];
      if (!s.active) { s.active = true; s.x = x; s.z = z; s.h = h; s.state = st; s.dT = 0; }
      s.tx = x; s.tz = z; s.th = h;
      if (st === 1 && s.state !== 1) s.dT = 0; // just started dying
      s.state = st;
      const k = Math.min(1, dt * 10);
      s.x += (s.tx - s.x) * k; s.z += (s.tz - s.z) * k;
      let dh = s.th - s.h; dh = Math.atan2(Math.sin(dh), Math.cos(dh)); s.h += dh * k;
      s.hitT = Math.max(0, s.hitT - dt);
      if (s.state === 1) s.dT += dt; else s.phase += dt * 9;
    } else s.active = false;
    placeJavelina(i, s);
  }
  javBodyMesh.instanceMatrix.needsUpdate = true; javLegMesh.instanceMatrix.needsUpdate = true;
}
